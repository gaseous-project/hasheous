using System.Reflection;
using System.Text.Json;
using Classes;
using hasheous_server.Models;

namespace hasheous_server.Classes
{
    public class Localisation
    {
        private static readonly List<LocalisationItem> LocalisationItems = new List<LocalisationItem>();

        /// <summary>
        /// Retrieves a list of all available localisation items.
        /// </summary>
        /// <returns>A task representing the asynchronous operation, containing a list of localisation items.</returns>
        public static async Task<List<LocalisationItem>> GetLanguages()
        {
            List<LocalisationItem> languages = new List<LocalisationItem>();
            foreach (var item in LocalisationItems)
            {
                languages.Add(new LocalisationItem
                {
                    FullCode = item.FullCode,
                    EnglishName = item.EnglishName,
                    NativeName = item.NativeName,
                    EnglishRegionName = item.EnglishRegionName,
                    NativeRegionName = item.NativeRegionName,
                    Direction = item.Direction,
                    Version = item.Version
                });
            }

            // sort the new list by FullCode
            languages.Sort((x, y) => string.Compare(x.FullCode, y.FullCode, StringComparison.Ordinal));

            return languages;
        }

        /// <summary>
        /// Retrieves a localisation item for the specified locale.
        /// </summary>
        /// <param name="locale">The locale code for the localisation item to retrieve.</param>
        /// <returns>A task representing the asynchronous operation.</returns>
        /// <remarks>
        /// It is assumed that the locale provided is in a valid format and corresponds to a supported language.
        /// Devolution rules as follows:
        /// 1. Check if the localisation item exists in LocalisationItems.
        /// 2. If not found, check if the localisation item exists in the database.
        /// 3. If not found, check the local file system for a JSON file corresponding to the locale.
        /// 4. If still not found, check the embedded JSON files - NOTE: only en will be embedded.
        /// 5. If the localisation item is found in any of these sources, add it to LocalisationItems and return it.
        /// 6. If the localisation item cannot be found, return null or throw an appropriate exception.
        /// Notes:
        /// - The AIGenerated field in the localisation strings indicates whether the translation was generated by AI.
        /// - Languages loaded from resource or disk are considered authoritative unless overridden by database entries.
        /// - Language files with a newer timestamp will override older entries from the database or embedded resources. Date is compared against the file's last modified timestamp and the updated_at timestamp in the database for the language or language variant.
        /// - Language strings loaded from files will set "AIGenerated" to false, indicating they are not AI-generated.
        /// - Language strings loaded from the database may have "AIGenerated" set to true if they were generated by AI.
        /// - Locales that aren't found will be queued for AI generation - this will include the base language and all known variants.
        /// - Language strings that aren't in the database will be queued for AI generation - again for the base language and all known variants.
        /// - The AI generation queue will be processed asynchronously to update the database with newly generated translations.
        /// </remarks>
        public static async Task<LocalisationItem> GetLocalisationItem(string locale)
        {
            // Check if the localisation item for the specified locale is already loaded - return immediately if found
            if (LocalisationItems.Any(item => item.LanguageCode == locale))
            {
                return LocalisationItems.First(item => item.LanguageCode == locale);
            }

            // If the localisation item is not already loaded, attempt to load it from the database, local file system, or embedded JSON files
            LocalisationItem? itemFromDatabase = await LoadLocalisationItemFromDatabaseAsync(locale);
            if (itemFromDatabase != null)
            {
                return itemFromDatabase;
            }

            // If the localisation item is not found in the database, check the local file system
            LocalisationItem? itemFromLocalFile = await LoadLocalisationItemFromLocalFileAsync(locale);
            if (itemFromLocalFile != null)
            {
                // save the localisation item to the database
                await ImportLocalisationFileAsync(itemFromLocalFile);

                return itemFromLocalFile;
            }

            // if the localisation is not found in the file system, check the embedded resources - note this is only for en
            if (locale == "en")
            {
                LocalisationItem? itemFromEmbedded = await LoadLocalisationItemFromEmbeddedResourceAsync(locale);
                if (itemFromEmbedded != null)
                {
                    // save the localisation item to the database
                    await ImportLocalisationFileAsync(itemFromEmbedded);

                    return itemFromEmbedded;
                }
            }

            throw new NotFoundException($"Localisation language not found for locale: {locale}");
        }

        private static async Task<LocalisationItem?> LoadLocalisationItemFromDatabaseAsync(string locale)
        {
            string sql = $"SELECT * FROM localisation_languages WHERE FullCode = @FullCode";
            Dictionary<string, object> parameters = new Dictionary<string, object>
            {
                { "FullCode", locale }
            };
            List<Dictionary<string, object>> localisationLanguageList = await Config.database.ExecuteCMDDictAsync(sql, parameters);
            if (localisationLanguageList != null && localisationLanguageList.Count > 0)
            {
                Dictionary<string, object> localisationLanguage = localisationLanguageList[0];
                LocalisationItem item = new LocalisationItem
                {
                    FullCode = localisationLanguage["FullCode"].ToString(),
                    Version = int.Parse(localisationLanguage["Version"].ToString()),
                    EnglishName = localisationLanguage["EnglishName"].ToString(),
                    NativeName = localisationLanguage["NativeName"].ToString(),
                    EnglishRegionName = localisationLanguage["EnglishRegionName"]?.ToString(),
                    NativeRegionName = localisationLanguage["NativeRegionName"]?.ToString(),
                    Direction = Enum.Parse<LocalisationItem.LanguageDirection>((int.Parse(localisationLanguage["Direction"].ToString())).ToString())
                };

                // load translations
                string translationsSql = $"SELECT * FROM localisation_strings WHERE language_id = @language_id";
                Dictionary<string, object> translationsParameters = new Dictionary<string, object>
                {
                    { "language_id", localisationLanguage["id"] }
                };
                List<Dictionary<string, object>> translationsList = await Config.database.ExecuteCMDDictAsync(translationsSql, translationsParameters);
                if (translationsList != null && translationsList.Count > 0)
                {
                    foreach (var translation in translationsList)
                    {
                        item.Translations.Add(translation["key"].ToString(), new LocalisationItem.TranslationItem
                        {
                            Value = translation["value"].ToString(),
                            AITranslated = bool.Parse(translation["AIGenerated"].ToString()),
                            CreatedAt = DateTime.Parse(translation["created_at"].ToString()),
                            UpdatedAt = DateTime.Parse(translation["updated_at"].ToString())
                        });
                    }
                }

                // remove any existing localisation item with the same language code from the in-memory collection
                LocalisationItems.RemoveAll(i => i.LanguageCode == item.LanguageCode);

                // add the localisation item to the in-memory collection
                LocalisationItems.Add(item);
                return item;
            }

            return null;
        }

        private static async Task<LocalisationItem?> LoadLocalisationItemFromLocalFileAsync(string locale)
        {
            string localFilePath = Path.Combine(Config.LibraryConfiguration.LibraryLocalisationDirectory, $"{locale}.json");
            if (System.IO.File.Exists(localFilePath))
            {
                string json = await System.IO.File.ReadAllTextAsync(localFilePath);
                LocalisationItem item = Newtonsoft.Json.JsonConvert.DeserializeObject<LocalisationItem>(json);
                if (item != null)
                {
                    item = ConvertStringsToTranslationItem(item);

                    // remove any existing localisation item with the same language code from the in-memory collection
                    LocalisationItems.RemoveAll(i => i.LanguageCode == item.LanguageCode);
                    // add the localisation item to the in-memory collection
                    LocalisationItems.Add(item);

                    return item;
                }
            }

            return null;
        }

        private static async Task<LocalisationItem?> LoadLocalisationItemFromEmbeddedResourceAsync(string locale)
        {
            string resourceName = $"hasheous.localisation.{locale}.json";
            Assembly assembly = Assembly.GetExecutingAssembly();
            using Stream? stream = assembly.GetManifestResourceStream(resourceName);
            if (stream != null)
            {
                using StreamReader reader = new StreamReader(stream);
                string json = await reader.ReadToEndAsync();
                LocalisationItem item = Newtonsoft.Json.JsonConvert.DeserializeObject<LocalisationItem>(json);
                if (item != null)
                {
                    item = ConvertStringsToTranslationItem(item);

                    // remove any existing localisation item with the same language code from the in-memory collection
                    LocalisationItems.RemoveAll(i => i.LanguageCode == item.LanguageCode);

                    // add the localisation item to the in-memory collection
                    LocalisationItems.Add(item);

                    return item;
                }
            }

            return null;
        }

        /// <summary>
        /// Imports the provided localisation item into the database, updating existing entries or adding new ones as necessary.
        /// </summary>
        /// <param name="item">The localisation item to import into the database loaded from disk or embedded resource</param>
        /// <returns>
        /// A task representing the asynchronous operation of importing the localisation item into the database.
        /// </returns>
        /// <remarks>
        /// This method will check for existing entries in the database and update them if necessary, or add new entries if they do not exist. It will generally be run as a background task.
        /// </remarks>
        private static async Task ImportLocalisationFileAsync(LocalisationItem item)
        {
            if (item == null)
            {
                throw new ArgumentNullException(nameof(item));
            }

            // check required values are present
            if (string.IsNullOrWhiteSpace(item.LanguageCode))
            {
                throw new InvalidOperationException("Localisation item has no language code.");
            }
            if (string.IsNullOrWhiteSpace(item.EnglishName))
            {
                throw new InvalidOperationException("Localisation item has no English name.");
            }
            if (string.IsNullOrWhiteSpace(item.NativeName))
            {
                throw new InvalidOperationException("Localisation item has no native name.");
            }

            // copy strings attribute into the Translations attribute and then clear the strings attribute
            if (item.Strings == null)
            {
                // this shouldn't happen - the file must be bad
                throw new InvalidOperationException("Localisation item has no strings.");
            }
            DateTime now = DateTime.UtcNow;

            // import the item into the database
            LocalisationItem? existingItem = await LoadLocalisationItemFromDatabaseAsync(item.LanguageCode);
            if (existingItem == null)
            {
                // full import
                string langHeaderSQL = "INSERT INTO localisation_languages (FullCode, Version, EnglishName, NativeName, EnglishRegionName, NativeRegionName, Direction, created_at, updated_at) VALUES (@FullCode, @Version, @EnglishName, @NativeName, @EnglishRegionName, @NativeRegionName, @Direction, @CreatedAt, @UpdatedAt); SELECT LAST_INSERT_ID();";
                Dictionary<string, object> langHeaderParams = new Dictionary<string, object>
                {
                    { "@FullCode", item.FullCode },
                    { "@Version", item.Version },
                    { "@EnglishName", item.EnglishName },
                    { "@NativeName", item.NativeName },
                    { "@EnglishRegionName", item.EnglishRegionName ?? "" },
                    { "@NativeRegionName", item.NativeRegionName ?? "" },
                    { "@Direction", item.Direction },
                    { "@CreatedAt", now },
                    { "@UpdatedAt", now }
                };
                var langHeaderIdTable = await Config.database.ExecuteCMDAsync(langHeaderSQL, langHeaderParams);
                int langHeaderId = int.Parse(langHeaderIdTable.Rows[0][0].ToString());

                foreach (var translation in item.Translations)
                {
                    string translationSQL = "INSERT INTO localisation_strings (language_id, `key`, `value`, AIGenerated, created_at, updated_at) VALUES (@LanguageId, @Key, @Value, @AIGenerated, @CreatedAt, @UpdatedAt);";
                    Dictionary<string, object> translationParams = new Dictionary<string, object>
                    {
                        { "@LanguageId", langHeaderId },
                        { "@Key", translation.Key },
                        { "@Value", translation.Value.Value },
                        { "@AIGenerated", translation.Value.AITranslated },
                        { "@CreatedAt", now },
                        { "@UpdatedAt", now }
                    };
                    await Config.database.ExecuteCMDAsync(translationSQL, translationParams);
                }
            }
            else
            {
                // verify the incoming item version is higher than the existing one before updating the existing localisation language entry
                string existingVersionSQL = "SELECT id, version FROM localisation_languages WHERE language_code = @LanguageCode;";
                Dictionary<string, object> existingVersionParams = new Dictionary<string, object>
                {
                    { "@LanguageCode", item.LanguageCode }
                };
                var existingVersionTable = await Config.database.ExecuteCMDAsync(existingVersionSQL, existingVersionParams);
                int existingVersion = int.Parse(existingVersionTable.Rows[0]["Version"].ToString());
                if (item.Version > existingVersion)
                {
                    // update the existing localisation language entry with the new version and other details
                    string updateSQL = "UPDATE localisation_languages SET EnglishName = @EnglishName, NativeName = @NativeName, EnglishRegionName = @EnglishRegionName, NativeRegionName = @NativeRegionName, Direction = @Direction, Version = @Version, updated_at = @UpdatedAt WHERE id = @id;";
                    Dictionary<string, object> updateParams = new Dictionary<string, object>
                    {
                        { "@EnglishName", item.EnglishName },
                        { "@NativeName", item.NativeName },
                        { "@EnglishRegionName", item.EnglishRegionName },
                        { "@NativeRegionName", item.NativeRegionName },
                        { "@Direction", item.Direction },
                        { "@Version", item.Version },
                        { "@UpdatedAt", now },
                        { "@id", existingVersionTable.Rows[0]["id"] }
                    };
                    await Config.database.ExecuteCMDAsync(updateSQL, updateParams);

                    foreach (var translation in item.Translations)
                    {
                        string updateTranslationSQL = "UPDATE localisation_translations SET Value = @Value, AITranslated = @AITranslated, UpdatedAt = @UpdatedAt WHERE language_id = @language_id AND Key = @Key;";
                        Dictionary<string, object> updateTranslationParams = new Dictionary<string, object>
                        {
                            { "@Value", translation.Value.Value },
                            { "@AITranslated", translation.Value.AITranslated },
                            { "@UpdatedAt", now },
                            { "@language_id", existingVersionTable.Rows[0]["id"] },
                            { "@Key", translation.Key }
                        };
                        await Config.database.ExecuteCMDAsync(updateTranslationSQL, updateTranslationParams);
                    }
                }
            }
        }

        private static LocalisationItem ConvertStringsToTranslationItem(LocalisationItem localisationItem)
        {
            localisationItem.Translations = new Dictionary<string, LocalisationItem.TranslationItem>();
            foreach (var kvp in localisationItem.Strings)
            {
                localisationItem.Translations.Add(kvp.Key, new LocalisationItem.TranslationItem
                {
                    Value = kvp.Value,
                    AITranslated = false,
                    CreatedAt = DateTime.UtcNow,
                    UpdatedAt = DateTime.UtcNow
                });
            }
            localisationItem.Strings.Clear();
            return localisationItem;
        }

        [Serializable]
        internal class NotFoundException : Exception
        {
            public NotFoundException()
            {
            }

            public NotFoundException(string? message) : base(message)
            {
            }

            public NotFoundException(string? message, Exception? innerException) : base(message, innerException)
            {
            }
        }
    }
}