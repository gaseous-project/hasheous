namespace hasheous_server.Models
{
    /// <summary>
    /// Represents a localisation item containing language and region information, as well as the localisation strings and translations.
    /// </summary>
    public class LocalisationItem
    {
        /// <summary>
        /// The direction of the language, either left-to-right or right-to-left.
        /// </summary>
        public enum LanguageDirection
        {
            /// <summary>
            /// The language is written from left to right.
            /// </summary>
            LeftToRight = 0,

            /// <summary>
            /// The language is written from right to left.
            /// </summary>
            RightToLeft = 1
        }

        /// <summary>
        /// The full language code for this localisation item, e.g., "en-US" for English (United States).
        /// </summary>
        public string FullCode { get; set; }

        /// <summary>
        /// The version of the localisation item.
        /// </summary>
        public int Version { get; set; } = 1;

        /// <summary>
        /// The language code for this localisation item, e.g., "en" for English.
        /// </summary>
        public string LanguageCode
        {
            get
            {
                return FullCode?.Split('-').ElementAtOrDefault(0);
            }
        }
        /// <summary>
        /// The English name of the language.
        /// </summary>
        public string? EnglishName { get; set; }
        /// <summary>
        /// The native name of the language.
        /// </summary>
        public string? NativeName { get; set; }
        /// <summary>
        /// The region code for this localisation item, e.g., "US" for the United States.
        /// </summary>
        public string? RegionCode
        {
            get
            {
                return FullCode?.Split('-').ElementAtOrDefault(1);
            }
        }

        /// <summary>
        /// The English name of the region.
        /// </summary>
        public string? EnglishRegionName { get; set; }
        /// <summary>
        /// The native name of the region.
        /// </summary>
        public string? NativeRegionName { get; set; }
        /// <summary>
        /// The direction of the language, either left-to-right or right-to-left.
        /// </summary>
        public LanguageDirection Direction { get; set; } = LanguageDirection.LeftToRight;

        /// <summary>
        /// The dictionary containing the localisation strings for this item. The key is the string identifier, and the value is the translated string.
        /// </summary>
        /// <remarks>
        /// This dictionary is only used for importing from files and should not be modified directly at runtime.
        /// </remarks>
        public Dictionary<string, string> Strings { get; set; } = new Dictionary<string, string>();

        /// <summary>
        /// The dictionary containing the translation items for this localisation item. The key is the string identifier, and the value is the translation item.
        /// </summary>
        public Dictionary<string, TranslationItem> Translations { get; set; } = new Dictionary<string, TranslationItem>();

        /// <summary>
        /// Represents a single translation item within a localisation item.
        /// </summary>
        public class TranslationItem
        {
            /// <summary>
            /// The translated value for the key.
            /// </summary>
            public string? Value { get; set; }
            /// <summary>
            /// Indicates whether this translation was generated by AI.
            /// </summary>
            public bool AITranslated { get; set; } = false;
            /// <summary>
            /// The timestamp when this translation item was created.
            /// </summary>
            public DateTime? CreatedAt { get; set; } = DateTime.UtcNow;
            /// <summary>
            /// The timestamp when this translation item was last updated.
            /// </summary>
            public DateTime? UpdatedAt { get; set; } = DateTime.UtcNow;
        }
    }
}